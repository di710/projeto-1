import pandas as pd
import sqlite3
import plotly.express as px

base = pd.read_csv("credit_risk_dataset.csv", sep = ',', encoding= 'UTF-8')
conn = sqlite3.connect("credito_banco.db")
base.to_sql("tb_credito", conn, if_exists="replace", index=False)

