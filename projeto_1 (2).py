# Entender os motivos que levam os clientes a pedir credito.

query1 = """
SELECT
    loan_intent AS intencao_emprestimo,
    COUNT(*) AS total_solicitacoes,
    AVG(loan_amnt) AS valor_medio_emprestimo,
    AVG(loan_int_rate) AS taxa_juros_media
FROM tb_credito
GROUP BY loan_intent
ORDER BY total_solicitacoes DESC;
"""
resultado1 = pd.read_sql_query(query1, conn)
resultado1

# Validar o aumento progressivo da taxa de inadimplência por nota de risco (de A até G)

query2 = """
SELECT
    loan_grade AS risco,
    COUNT(*) AS qtd_clientes,
    SUM(loan_status) AS total_inadiplentes,
    AVG(Loan_status) * 100 AS pct_inadimplencia
FROM tb_credito
GROUP BY loan_grade
ORDER BY risco ASC;
"""

resultado2 = pd.read_sql_query(query2, conn)
resultado2

# Comparar clientes que moram de aluguel, casa propria ou financiada.

query3 = """
SELECT
    person_home_ownership AS moradia,
    COUNT(*) as qtd_clientes,
    AVG(person_income) AS renda_media,
    AVG(loan_amnt) AS valor_medio
FROM tb_credito
GROUP BY person_home_ownership
ORDER BY qtd_clientes;
"""

resultado3 = pd.read_sql_query(query3, conn)
resultado3

# Analisar as condições de crédito oferecidas para quem já teve problemas financeiros (Y = Sim | N = Não).

query4 = """
SELECT
    cb_person_default_on_file AS historico_sujo,
    COUNT(*) as qtd_clientes,
    AVG(loan_int_rate) AS media_juros,
    AVG(loan_amnt) AS media_valor
FROM tb_credito
GROUP BY cb_person_default_on_file;
"""

resultado4 = pd.read_sql_query(query4, conn)
resultado4

# Identificar se os clientes inadimplentes (1 = Inadimplente | 0 = Em dia) comprometem uma fatia maior da renda.

query5 = """
SELECT
    loan_status AS inadimplente,
    COUNT(*) AS qtd_clientes,
    AVG(loan_percent_income) * 100 AS comprometimento_renda_medio
FROM tb_credito
GROUP BY loan_status;
"""

resultado5 = pd.read_sql_query(query5, conn)
resultado5

# Avaliar se clientes com mais anos de historico no mercado bancario são mais confiaveis.

query6 = """
SELECT
    cb_person_cred_hist_length AS anos_historico,
    COUNT(*) AS total_clientes,
    SUM(loan_status) AS total_inadimplentes,
    AVG(loan_status) * 100 AS pct_inadimplencia
FROM tb_credito
GROUP BY cb_person_cred_hist_length
HAVING total_clientes > 100
ORDER BY anos_historico ASC;
"""
resultado6 = pd.read_sql_query(query6, conn)
